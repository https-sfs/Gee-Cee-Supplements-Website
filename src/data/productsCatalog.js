/** Map Products landing card slugs → Lovable catalogue slugs when they differ. */
const SLUG_ALIASES = {
  'waterproofing-coatings': 'waterproofing-systems',
  'expansion-joints-sealants': 'expansion-joints',
  'concrete-mortar-admixtures': 'concrete-admixtures',
}

export const resolveCategorySlug = (slug) => SLUG_ALIASES[slug] || slug

export const getCategory = (slug) => {
  const resolved = resolveCategorySlug(slug)
  return categories.find((c) => c.slug === resolved || c.slug === slug)
}

export const getProduct = (categorySlug, productSlug) => {
  const category = getCategory(categorySlug)
  return { category, product: category?.products.find((p) => p.slug === productSlug) }
}

export const allProducts = categories.flatMap((c) =>
  c.products.map((p) => ({ ...p, category: c })),
);
